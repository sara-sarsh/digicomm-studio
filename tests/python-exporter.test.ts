// tests/python-exporter.test.ts
import { describe, it, expect } from 'vitest';
import { ModulationType, SimConfig } from '../src/core/types';
import { generatePythonCode } from '../src/export/python-exporter';

describe('Python Code Exporter (Phase 2)', () => {
  const baseConfig: SimConfig = {
    modulation: ModulationType.QPSK,
    snrMin: 0,
    snrMax: 10,
    snrStep: 2,
    symbolCount: 50000,
  };

  it('Generated AWGN script contains scipy.special.erfc and common boilerplate', () => {
    const script = generatePythonCode({ ...baseConfig, simType: 'awgn' });
    expect(script).toContain('scipy.special.erfc');
    expect(script).toContain('Generated by DigiComm Studio');
    expect(script).toContain("if __name__ == '__main__':");
    expect(script).toContain('import numpy as np');
    expect(script).toContain('import matplotlib.pyplot as plt');
    expect(script).toContain('import scipy.special as sp');
  });

  it('Generated Rayleigh script contains rayleigh or fading', () => {
    const script = generatePythonCode({ ...baseConfig, simType: 'rayleigh' });
    const hasRayleighOrFading = script.toLowerCase().includes('rayleigh') || script.toLowerCase().includes('fading');
    expect(hasRayleighOrFading).toBe(true);
    expect(script).toContain('Generated by DigiComm Studio');
    expect(script).toContain("if __name__ == '__main__':");
  });

  it('Generated OFDM script contains np.fft.ifft and np.fft.fft', () => {
    const script = generatePythonCode({
      ...baseConfig,
      simType: 'ofdm',
      ofdmSubcarriers: 64,
      ofdmCpLength: 16,
    });
    expect(script).toContain('np.fft.ifft');
    expect(script).toContain('np.fft.fft');
    expect(script).toContain('CP_LENGTH = 16');
    expect(script).toContain('Generated by DigiComm Studio');
    expect(script).toContain("if __name__ == '__main__':");
  });

  it('Generated Coded and MIMO scripts contain correct algorithms and guards', () => {
    const codedScript = generatePythonCode({ ...baseConfig, simType: 'coded' });
    expect(codedScript).toContain('Hamming');
    expect(codedScript).toContain('Generated by DigiComm Studio');
    expect(codedScript).toContain("if __name__ == '__main__':");

    const mimoScript = generatePythonCode({ ...baseConfig, simType: 'mimo' });
    expect(mimoScript).toContain('Alamouti');
    expect(mimoScript).toContain('Generated by DigiComm Studio');
    expect(mimoScript).toContain("if __name__ == '__main__':");
  });

  it('Generated scripts all contain Generated by DigiComm Studio and if __name__', () => {
    const simTypes: SimConfig['simType'][] = ['awgn', 'rayleigh', 'ofdm', 'coded', 'mimo'];
    for (const simType of simTypes) {
      const script = generatePythonCode({ ...baseConfig, simType });
      expect(script).toContain('Generated by DigiComm Studio');
      expect(script).toContain("if __name__ == '__main__':");
    }
  });
});
