// tests/python-exporter.test.ts
import { describe, it, expect } from 'vitest';
import { ModulationType } from '../src/core/types';
import { generatePythonCode } from '../src/export/python-exporter';

describe('Python Code Exporter', () => {
  it('generates a complete valid Python script with required imports and parameters', () => {
    const config = {
      modulation: ModulationType.QPSK,
      snrMin: 0,
      snrMax: 10,
      snrStep: 2,
      symbolCount: 50000
    };

    const script = generatePythonCode(config);

    expect(script).toContain('#!/usr/bin/env python3');
    expect(script).toContain('# Generated by DigiComm Studio');
    expect(script).toContain('import numpy as np');
    expect(script).toContain('import matplotlib.pyplot as plt');
    expect(script).toContain('import scipy.special as sp');
    expect(script).toContain('SNR_MIN = 0');
    expect(script).toContain('SNR_MAX = 10');
    expect(script).toContain('SNR_STEP = 2');
    expect(script).toContain('NUM_SYMBOLS = 50000');
    expect(script).toContain('plt.semilogy(');
  });
});
