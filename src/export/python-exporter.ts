import { ModulationType, SimConfig } from '../core/types';

function getModulationName(mod: ModulationType): string {
  switch (mod) {
    case ModulationType.BPSK:
      return 'BPSK';
    case ModulationType.QPSK:
      return 'QPSK';
    case ModulationType.QAM16:
      return '16-QAM';
    case ModulationType.QAM64:
      return '64-QAM';
  }
}

export function generatePythonCode(config: SimConfig): string {
  const modName = getModulationName(config.modulation);

  return `#!/usr/bin/env python3
# ==============================================================================
# Generated by DigiComm Studio
# Digital Communications Simulation Lab (Proakis & Salehi 5th Ed.)
#
# Configuration:
# Modulation: ${modName}
# SNR range: ${config.snrMin} dB to ${config.snrMax} dB (step: ${config.snrStep} dB)
# Symbol count per SNR: ${config.symbolCount}
# ==============================================================================

import numpy as np
import matplotlib.pyplot as plt
import scipy.special as sp

# ------------------------------------------------------------------------------
# 1. Modulation & Constellation Setup
# ------------------------------------------------------------------------------
MOD_TYPE = ${config.modulation}  # 0: BPSK, 1: QPSK, 2: 16-QAM, 3: 64-QAM
SNR_MIN = ${config.snrMin}
SNR_MAX = ${config.snrMax}
SNR_STEP = ${config.snrStep}
NUM_SYMBOLS = ${config.symbolCount}

def generate_constellation(mod_type):
    if mod_type == 0:  # BPSK
        return np.array([-1.0 + 0j, 1.0 + 0j]), 1
    elif mod_type == 1:  # QPSK
        scale = 1.0 / np.sqrt(2.0)
        # Gray coded: 00, 01, 11, 10
        levels = np.array([-scale, scale])
        points = []
        for s in range(4):
            r = (s >> 1) ^ (s >> 2)  # Gray decoding
            c = (s & 1) ^ ((s >> 1) & 1)
            # Standard QPSK
            i_val = -scale if (s >> 1) == 0 else scale
            q_val = -scale if (s & 1) == 0 else scale
            points.append(i_val + 1j * q_val)
        return np.array(points), 2
    elif mod_type == 2:  # 16-QAM
        scale = 1.0 / np.sqrt(10.0)
        pam4 = np.array([-3, -1, 1, 3]) * scale
        gray4 = [0, 1, 3, 2]
        points = []
        for i in range(4):
            for q in range(4):
                points.append(pam4[gray4[i]] + 1j * pam4[gray4[q]])
        return np.array(points), 4
    elif mod_type == 3:  # 64-QAM
        scale = 1.0 / np.sqrt(42.0)
        pam8 = np.array([-7, -5, -3, -1, 1, 3, 5, 7]) * scale
        gray8 = [0, 1, 3, 2, 6, 7, 5, 4]
        points = []
        for i in range(8):
            for q in range(8):
                points.append(pam8[gray8[i]] + 1j * pam8[gray8[q]])
        return np.array(points), 6

def q_function(x):
    return 0.5 * sp.erfc(x / np.sqrt(2.0))

def theoretical_ber(snr_db, mod_type):
    snr_lin = 10.0 ** (snr_db / 10.0)
    if mod_type in (0, 1):  # BPSK or QPSK
        return q_function(np.sqrt(2.0 * snr_lin))
    elif mod_type == 2:  # 16-QAM
        return 0.75 * sp.erfc(np.sqrt(snr_lin * 0.4))
    elif mod_type == 3:  # 64-QAM
        return (7.0 / 12.0) * sp.erfc(np.sqrt(snr_lin * (1.0 / 21.0)))

# ------------------------------------------------------------------------------
# 2. Monte Carlo Simulation Loop
# ------------------------------------------------------------------------------
def run_simulation():
    np.random.seed(42)
    constellation, k_bits = generate_constellation(MOD_TYPE)
    M = len(constellation)

    snr_range = np.arange(SNR_MIN, SNR_MAX + 1e-5, SNR_STEP)
    ber_sim = []
    ber_theo = []

    print(f"Starting simulation for {${JSON.stringify(modName)}} with {NUM_SYMBOLS} symbols per SNR...")

    for snr_db in snr_range:
        snr_lin = 10.0 ** (snr_db / 10.0)
        # Noise variance per dimension: N0 / 2 = 1 / (2 * k * Eb/N0)
        sigma = np.sqrt(1.0 / (2.0 * k_bits * snr_lin))

        # Transmit random symbols
        sent_indices = np.random.randint(0, M, size=NUM_SYMBOLS)
        tx_symbols = constellation[sent_indices]

        # Add Complex AWGN Noise
        noise = sigma * (np.random.randn(NUM_SYMBOLS) + 1j * np.random.randn(NUM_SYMBOLS))
        rx_symbols = tx_symbols + noise

        # Minimum Euclidean Distance Detector
        # Shape: (NUM_SYMBOLS, M)
        dists = np.abs(rx_symbols[:, np.newaxis] - constellation[np.newaxis, :]) ** 2
        detected_indices = np.argmin(dists, axis=1)

        # Bit error calculation (XOR bits differences)
        xor_diff = sent_indices ^ detected_indices
        bit_errors = 0
        for val in xor_diff:
            bit_errors += bin(val).count("1")

        total_bits = NUM_SYMBOLS * k_bits
        ber = max(1e-7, bit_errors / total_bits)
        theo = theoretical_ber(snr_db, MOD_TYPE)

        ber_sim.append(ber)
        ber_theo.append(theo)
        print(f"SNR: {snr_db:5.1f} dB | BER Sim: {ber:.2e} | BER Theo: {theo:.2e}")

    # --------------------------------------------------------------------------
    # 3. Plotting Results
    # --------------------------------------------------------------------------
    plt.figure(figsize=(9, 6))
    plt.semilogy(snr_range, ber_sim, 'o-', color='#3b82f6', label='Simulated BER', linewidth=2, markersize=6)
    plt.semilogy(snr_range, ber_theo, '--', color='#ef4444', label='Theoretical BER (Proakis)', linewidth=2)
    plt.grid(True, which='both', linestyle=':', alpha=0.6)
    plt.xlabel('SNR $E_b/N_0$ (dB)', fontsize=12)
    plt.ylabel('Bit Error Rate (BER)', fontsize=12)
    plt.title(f'DigiComm Studio: {${JSON.stringify(modName)}} Performance in AWGN', fontsize=14, fontweight='bold')
    plt.ylim([1e-6, 1.0])
    plt.legend(fontsize=11)
    plt.tight_layout()
    plt.show()

if __name__ == '__main__':
    run_simulation()
`;
}
